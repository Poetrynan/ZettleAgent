#!/usr/bin/env node
/**
 * Regenerates src-tauri/src/db/cjk_fold_table.rs from OpenCC's
 * TSCharacters.txt (traditional → simplified, one character at a time).
 *
 *   node scripts/gen-cjk-fold-table.cjs <path/to/TSCharacters.txt> [opencc-commit]
 *
 * Source: https://github.com/BYVoid/OpenCC/blob/master/data/dictionary/TSCharacters.txt
 * License of the data: Apache-2.0 (same as this project).
 *
 * Rules:
 * - `key<TAB>v1 v2 ...`: v1 is OpenCC's preferred conversion. When v1 equals
 *   the key, OpenCC keeps the character as is, so no pair is emitted.
 * - Only single code point keys and values are kept (search folds per char).
 * - Output is sorted by code point for binary search.
 */
const fs = require('fs');
const path = require('path');

const [, , input, commit = 'unknown'] = process.argv;
if (!input) {
  console.error('usage: gen-cjk-fold-table.cjs <TSCharacters.txt> [opencc-commit]');
  process.exit(1);
}

const pairs = new Map();
for (const line of fs.readFileSync(input, 'utf8').split(/\r?\n/)) {
  if (!line || line.startsWith('#')) continue;
  const [key, values] = line.split('\t');
  if (!key || !values) continue;
  const first = values.trim().split(/\s+/)[0];
  if ([...key].length !== 1 || [...first].length !== 1 || first === key) continue;
  pairs.set(key.codePointAt(0), first.codePointAt(0));
}

// Fold must be idempotent: if a target is itself a key, follow the chain.
let chained = 0;
for (const [k, v] of pairs) {
  let t = v;
  const seen = new Set([k]);
  while (pairs.has(t) && !seen.has(t)) { seen.add(t); t = pairs.get(t); }
  if (t !== v) { pairs.set(k, t); chained++; }
}
if (chained) console.log(`resolved ${chained} chained mappings`);

const esc = (cp) => `'\\u{${cp.toString(16).toUpperCase()}}'`;
const rows = [...pairs.entries()].sort((a, b) => a[0] - b[0]);
const out = `// @generated by scripts/gen-cjk-fold-table.cjs — do not edit by hand.
//
// Traditional → simplified Chinese, one character each, from OpenCC
// TSCharacters.txt (commit ${commit}).
// OpenCC (https://github.com/BYVoid/OpenCC), Apache License 2.0
// (https://github.com/BYVoid/OpenCC/blob/master/LICENSE).
//
// ${rows.length} pairs, sorted by key for binary search.

pub(super) static TRAD_TO_SIMP: &[(char, char)] = &[
${rows.map(([k, v]) => `    (${esc(k)}, ${esc(v)}),`).join('\n')}
];
`;
const dest = path.join(__dirname, '..', 'src-tauri', 'src', 'db', 'cjk_fold_table.rs');
fs.writeFileSync(dest, out);
console.log(`wrote ${rows.length} pairs to ${path.relative(process.cwd(), dest)}`);
